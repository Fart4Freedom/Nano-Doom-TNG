// Bit / mask sampling helper, including frame offset. No SRAM allocations.
static inline uint8_t doom_sprite_pixel(const uint8_t *plane,
                                        uint8_t width, uint8_t height,
                                        uint8_t frame, uint8_t x, uint8_t y) {
    if (x >= width || y >= height) return 0;
    uint16_t stride = ((uint16_t)width + 7u) / 8u;
    uint16_t pos = (uint16_t)frame * stride * height + (uint16_t)y * stride + (x >> 3);
    return (pgm_read_byte(plane + pos) & (uint8_t)(0x80u >> (x & 7u))) != 0;
}


